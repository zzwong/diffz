#!/usr/bin/env python3
"""Refresh the vendored Linux target after changing Cargo's locked dependency graph."""
import json
from pathlib import Path
import subprocess

root = Path(__file__).resolve().parent.parent
metadata = json.loads(subprocess.check_output([
    "cargo", "metadata", "--locked", "--all-features", "--filter-platform",
    "x86_64-unknown-linux-gnu", "--format-version", "1",
], cwd=root))
packages = {package["id"]: package for package in metadata["packages"]}
package = next(p for p in packages.values() if p["name"] == "gpui-pre-linux")
node = next(n for n in metadata["resolve"]["nodes"] if n["id"] == package["id"])
deps, aliases = [], {}
active_optional = set()
for feature in node["features"]:
    for member in package["features"].get(feature, []):
        if member.startswith("dep:"):
            active_optional.add(member[4:])
        elif "/" in member and "?/" not in member:
            active_optional.add(member.split("/")[0])
    active_optional.add(feature)
optional = {d.get("rename") or d["name"] for d in package["dependencies"] if d["optional"]}
for dep in node["deps"]:
    if not any(kind["kind"] is None for kind in dep["dep_kinds"]):
        continue
    # Cargo metadata can retain inactive weak optional edges (e.g. scap?/x11).
    if dep["name"] in optional and dep["name"] not in active_optional:
        continue
    pkg = packages[dep["pkg"]]
    target = next(t for t in pkg["targets"] if "lib" in t["kind"] or "proc-macro" in t["kind"])
    if "proc-macro" in target["kind"]:
        raise SystemExit("New Linux proc-macro dependency requires a proc_macro_deps entry")
    label = f'@@rules_rust++crate+crates__{pkg["name"]}-{pkg["version"]}//:{target["name"]}'
    deps.append(label)
    if dep["name"] != target["name"]:
        aliases[label] = dep["name"]

output = '''"""Generated by scripts/bazel-vendor-linux.py; do not edit dependency pins by hand."""
load("@rules_rust//rust:defs.bzl", "rust_library")

def vendor_linux():
    rust_library(
        name = "gpui_linux",
        visibility = ["//visibility:public"],
        crate_name = "gpui_linux",
        edition = "2024",
        crate_root = "//vendor/gpui-pre-linux:src/gpui_linux.rs",
        srcs = ["//vendor/gpui-pre-linux:rust_sources"],
        compile_data = ["Cargo.toml", "crates/core/Cargo.toml", "crates/adapters/Cargo.toml", "crates/ui/Cargo.toml", "crates/app/Cargo.toml"] + ["//vendor/gpui-pre-linux:crate_data"],
        rustc_flags = ["-Cdebuginfo=1"],
'''
output += '        rustc_env = ' + repr({"CARGO_MANIFEST_DIR": "vendor/gpui-pre-linux", "CARGO_PKG_VERSION": package["version"]}) + ',\n'
output += '        deps = [\n' + ''.join(f'            {label!r},\n' for label in sorted(deps)) + '        ],\n'
output += f'        aliases = {aliases!r},\n        crate_features = {sorted(node["features"])!r},\n    )\n'
(root / "bazel/vendor_linux.bzl").write_text(output)
